import { readFile, writeFile } from "node:fs/promises";

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  throw new Error("usage: node generate-map.mjs INPUT.geojson OUTPUT.ts");
}

const geojson = JSON.parse(await readFile(inputPath, "utf8"));
if (geojson.type !== "FeatureCollection" || !Array.isArray(geojson.features)) {
  throw new Error("expected a GeoJSON FeatureCollection");
}

const round = (value) => Math.round(value * 100) / 100;
const point = ([longitude, latitude]) => `${round(longitude + 180)} ${round(90 - latitude)}`;

function ringPath(ring) {
  if (!Array.isArray(ring) || ring.length < 3) return "";
  const coordinates = [...ring];
  const first = coordinates[0];
  const last = coordinates.at(-1);
  if (first[0] === last[0] && first[1] === last[1]) coordinates.pop();
  return `M${coordinates.map(point).join("L")}Z`;
}

function polygonPath(polygon) {
  return polygon.map(ringPath).filter(Boolean).join("");
}

function geometryPath(geometry) {
  if (geometry?.type === "Polygon") return polygonPath(geometry.coordinates);
  if (geometry?.type === "MultiPolygon") {
    return geometry.coordinates.map(polygonPath).filter(Boolean).join("");
  }
  return "";
}

const countries = geojson.features
  .map((feature) => ({
    name: feature.properties?.NAME_EN ?? feature.properties?.NAME ?? "Unknown",
    path: geometryPath(feature.geometry),
  }))
  .filter(({ path }) => path)
  .sort((a, b) => a.name.localeCompare(b.name));

const source = `// Generated by scripts/generate-map.mjs from Natural Earth 1:110m data.\n` +
  `// Do not edit by hand.\n\n` +
  `export interface WorldMapCountry {\n  name: string;\n  path: string;\n}\n\n` +
  `export const worldMapCountries: WorldMapCountry[] = ${JSON.stringify(countries)};\n`;

await writeFile(outputPath, source);
console.log(`generated ${countries.length} countries in ${outputPath}`);
